import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
test('case learning, verified export, restart, deletion and restore work on a phone viewport', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 390, height: 844 }); await page.goto('/');
  await page.getByRole('tab', { name: 'Cases', exact: true }).click();
  await page.getByRole('textbox', { name: 'New case title', exact: true }).fill('Sensor bench');
  await page.getByRole('button', { name: 'Create case', exact: true }).click();
  await expect(page.getByText('LOCAL CASE · REVISION 1', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Load synthetic paired example', exact: true }).click();
  await page.getByRole('button', { name: 'Save original source', exact: true }).click();
  await expect(page.getByText('Original source retained exactly.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Learn and validate profile', exact: true }).click();
  await expect(page.getByText('Profile saved for this declared dataset. Physical validation remains unverified.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Prepare case export', exact: true }).click();
  const field = page.getByRole('textbox', { name: 'Verified case export', exact: true });
  await expect(field).toBeVisible(); const portable = await field.inputValue();
  const decoded = JSON.parse(portable); expect(decoded.artifacts).toHaveLength(3); expect(decoded.artifacts[0].origin).toBe('synthetic');
  expect(decoded.artifacts[2].parents).toHaveLength(2);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await mkdir('review-evidence/case-workspace', { recursive: true });
  await page.screenshot({ path: 'review-evidence/case-workspace/phone.png', fullPage: true });
  await page.reload(); await page.getByRole('tab', { name: 'Cases', exact: true }).click();
  await page.getByRole('button', { name: 'Open Sensor bench', exact: true }).click();
  await expect(page.getByText('LOCAL CASE · REVISION 4', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Delete this local case', exact: true })).toBeDisabled();
  await page.getByRole('textbox', { name: 'Case title to confirm deletion', exact: true }).fill('Sensor bench');
  await page.getByRole('button', { name: 'Delete this local case', exact: true }).click();
  await expect(page.getByText('Local case deleted.', { exact: true })).toBeVisible();
  const damaged = JSON.parse(portable); damaged.artifacts[0].content += 'x';
  await page.getByRole('textbox', { name: 'Case restore input', exact: true }).fill(JSON.stringify(damaged));
  await page.getByRole('button', { name: 'Verify and restore case', exact: true }).click();
  await expect(page.getByText('Case source digest mismatch', { exact: true })).toBeVisible();
  await page.getByRole('textbox', { name: 'Case restore input', exact: true }).fill(portable);
  await page.getByRole('button', { name: 'Verify and restore case', exact: true }).click();
  await expect(page.getByText('Case restored and verified.', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
test('two tabs cannot overwrite a newer case and unsaved input remains available', async ({ page, context }) => {
  await page.goto('/'); await page.getByRole('tab', { name: 'Cases', exact: true }).click();
  await page.getByRole('textbox', { name: 'New case title', exact: true }).fill('Concurrent');
  await page.getByRole('button', { name: 'Create case', exact: true }).click();
  await expect(page.getByText('LOCAL CASE · REVISION 1', { exact: true })).toBeVisible();
  const other = await context.newPage(); await other.goto('/'); await other.getByRole('tab', { name: 'Cases', exact: true }).click();
  await other.getByRole('button', { name: 'Open Concurrent', exact: true }).click();
  await page.getByRole('textbox', { name: 'Case source input', exact: true }).fill('first source');
  await page.getByRole('button', { name: 'Save original source', exact: true }).click();
  await expect(page.getByText('Original source retained exactly.', { exact: true })).toBeVisible();
  await other.getByRole('textbox', { name: 'Case source input', exact: true }).fill('second source');
  await other.getByRole('button', { name: 'Save original source', exact: true }).click();
  await expect(other.getByText(/Case changed in another view/)).toBeVisible();
  await expect(other.getByRole('textbox', { name: 'Case source input', exact: true })).toHaveValue('second source');
  await other.getByRole('button', { name: 'Reload cases', exact: true }).click();
  await expect(other.getByText('LOCAL CASE · REVISION 2', { exact: true })).toBeVisible();
  await other.getByRole('button', { name: 'Save original source', exact: true }).click();
  await expect(other.getByText('LOCAL CASE · REVISION 3', { exact: true })).toBeVisible();
});
